CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  cargo TEXT NOT NULL DEFAULT 'coordenacao',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS oficinas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  eixo_pedagogico TEXT NOT NULL,
  faixa_etaria TEXT NOT NULL,
  turno_disponivel TEXT NOT NULL,
  horario_referencia TEXT NOT NULL,
  educador_responsavel TEXT NOT NULL,
  descricao TEXT NOT NULL,
  objetivo_desenvolvimento TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS rotina_horarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turno TEXT NOT NULL,
  horario TEXT NOT NULL,
  atividade TEXT NOT NULL,
  detalhe_nutricional_pedagogico TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS visitas_agendadas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo TEXT NOT NULL UNIQUE,
  nome_responsavel TEXT NOT NULL,
  parentesco TEXT NOT NULL,
  telefone TEXT NOT NULL,
  faixa_etaria_crianca TEXT NOT NULL,
  turno_interesse TEXT NOT NULL,
  frequencia_semanal INTEGER NOT NULL,
  inclui_almoco BOOLEAN NOT NULL DEFAULT TRUE,
  possui_irmao BOOLEAN NOT NULL DEFAULT FALSE,
  mensalidade_estimada NUMERIC(10,2) NOT NULL,
  data_preferencia TEXT NOT NULL,
  consentimento_parental_lgpd BOOLEAN NOT NULL DEFAULT TRUE,
  status TEXT NOT NULL DEFAULT 'Visita Agendada',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS solicitacoes_lgpd (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo TEXT NOT NULL UNIQUE,
  nome_titular TEXT NOT NULL,
  email_titular TEXT NOT NULL,
  tipo_direito TEXT NOT NULL,
  detalhes TEXT,
  status TEXT NOT NULL DEFAULT 'Recebido',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE oficinas ENABLE ROW LEVEL SECURITY;
ALTER TABLE rotina_horarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE visitas_agendadas ENABLE ROW LEVEL SECURITY;
ALTER TABLE solicitacoes_lgpd ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Leitura publica de oficinas" ON oficinas FOR SELECT USING (true);
CREATE POLICY "Leitura publica de rotina" ON rotina_horarios FOR SELECT USING (true);
CREATE POLICY "Apenas backend gerencia visitas" ON visitas_agendadas FOR ALL USING (false);
